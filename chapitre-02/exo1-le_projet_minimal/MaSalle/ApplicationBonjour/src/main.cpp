#include <iostream>

// Programme minimal : il affiche un message simple à l'écran.
int main() {
    // std::cout permet d'écrire du texte dans la console.
    // << est l'opérateur de flux, et std::endl termine la ligne.
    std::cout << "bonjour" << std::endl;

    // 0 indique que le programme s'est terminé correctement.
    return 0;
}
